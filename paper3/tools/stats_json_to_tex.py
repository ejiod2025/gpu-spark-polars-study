#!/usr/bin/env python3
"""Paper 3: write generated/stats.tex from analyze_paper3.py's stats.json, for exactly the keys main.tex uses.

The paper cites a statistic as \\stat{key}, \\tstat{key}, \\ratiotext{prefix}, \\ratioci{prefix}, \\tratioci{prefix} or
\\xcell{prefix} (macros.tex). This tool scans main.tex for those, expands the prefixes (estimate, ci_low, ci_high; for \\xcell
estimate and class), flattens stats.json with the analysis's own outputs.flatten and formats every value with its own
outputs.tex_number, so a value reads the same here as in the analysis's tables. Keys of values from committed records, not
campaign outcomes (amend.*, campaign.*), are skipped: they come from the hand-kept generated/record.tex (macros.tex).

It refuses (exit 1) if a key the paper uses is absent from stats.json or is a list or object, unless --allow-missing; a synthetic
stats.json (_meta.synthetic true) writes \\syntheticstatstrue, which watermarks every page.

  stats_json_to_tex.py --stats OUT/stats.json [--tex main.tex] [--output generated/stats.tex] [--check] [--allow-missing]
  stats_json_to_tex.py --list-keys [--tex main.tex]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent
REPO = PAPER.parent
RECORD_PREFIXES = ("amend.", "campaign.")
MACRO_RE = re.compile(r"\\(stat|tstat|hashstat|ratioci|ratiotext|tratioci|xcell)\{([^}]+)\}")
EXPANSION = {"ratioci": ("estimate", "ci_low", "ci_high"), "ratiotext": ("estimate", "ci_low", "ci_high"),
             "tratioci": ("estimate", "ci_low", "ci_high"), "xcell": ("estimate", "class")}


def strip_comments(text: str) -> str:
    """Drop TeX comments (an unescaped % to the end of the line), so commented-out keys are not required."""
    return "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in text.splitlines())


def used_keys(tex_files) -> list:
    keys = set()
    for path in tex_files:
        for macro, arg in MACRO_RE.findall(strip_comments(Path(path).read_text())):
            fields = EXPANSION.get(macro)
            keys.update(f"{arg}.{f}" for f in fields) if fields else keys.add(arg)
    return sorted(keys)


def analysis_outputs():
    sys.path.insert(0, str(REPO))
    from paper3_analysis import outputs          # the analysis's own flattening and number format
    return outputs


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--stats", type=Path, help="analyze_paper3.py OUT/stats.json")
    parser.add_argument("--tex", type=Path, nargs="+", default=[PAPER / "main.tex"])
    parser.add_argument("--output", type=Path, default=PAPER / "generated" / "stats.tex")
    parser.add_argument("--list-keys", action="store_true", help="print every key the paper uses (record keys marked) and exit")
    parser.add_argument("--check", action="store_true", help="report missing keys, write nothing")
    parser.add_argument("--allow-missing", action="store_true", help="write the keys present; the build then fails on the others")
    args = parser.parse_args(argv)

    keys = used_keys(args.tex)
    if args.list_keys:
        for key in keys:
            print(f"{key}  (record.tex)" if key.startswith(RECORD_PREFIXES) else key)
        return 0
    if args.stats is None:
        parser.error("--stats is required (or --list-keys)")

    outputs = analysis_outputs()
    stats = json.loads(args.stats.read_text())
    flat = outputs.flatten(stats)
    wanted = [k for k in keys if not k.startswith(RECORD_PREFIXES)]
    missing = [k for k in wanted if k not in flat]
    not_scalar = [k for k in wanted if k in flat and isinstance(flat[k], (list, dict))]
    synthetic = bool((stats.get("_meta") or {}).get("synthetic"))
    print(f"{len(wanted)} keys used by the paper (plus {len(keys) - len(wanted)} from record.tex); "
          f"{len(missing)} missing from {args.stats}; {len(not_scalar)} not scalar; synthetic: {synthetic}", file=sys.stderr)
    for k in missing:
        print(f"  missing: {k}", file=sys.stderr)
    for k in not_scalar:
        print(f"  not a scalar: {k}", file=sys.stderr)
    if args.check:
        return 1 if missing or not_scalar else 0
    if (missing or not_scalar) and not args.allow_missing:
        return 1

    lines = [f"% generated by paper3/tools/stats_json_to_tex.py from {args.stats.name} -- do not edit",
             f"% analysis code sha256: {(stats.get('_meta') or {}).get('analysis_code_sha256')}"]
    if synthetic:
        lines += ["% SYNTHETIC - NOT RESULTS", "\\syntheticstatstrue"]
    for key in wanted:
        if key in flat and not isinstance(flat[key], (list, dict)):
            lines.append(f"\\defstat{{{key}}}{{{outputs.tex_number(key, flat[key])}}}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
