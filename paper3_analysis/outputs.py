def squares_rows(tree) -> list:
    rows = []
    for host, hd in sorted(tree.hosts.items()):
        for square, rounds in hd.square_rounds.items():
            owner = hd.complete.get(square)
            accepted = {i.label: sorted(r for r in rounds if r in i.accepted) for i in hd.instances}
            rows.append({"host": host, "square": square, "design_rounds": rounds, "complete": owner is not None, "instance": owner.label if owner else None,
                         "accepted_by_instance": accepted, "basis": "confirmatory" if owner else ("descriptive" if not hd.has_complete_square else "sensitivity")})
    return rows


