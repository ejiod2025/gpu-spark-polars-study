def cell_rows(store, rounds_of_interest=None) -> list:
    rows = []
    for c in store.cells:
        base = {"host": c.host, "instance": c.instance, "round": c.round, "suite": c.suite, "scale": c.scale, "query": c.query, "engine": c.engine,
                "time_s": c.time_s, "time_reason": c.time_reason, "trials": c.n_trials, "coverage": c.coverage}
        if not c.energy:
            rows.append({**base})
        for series, e in sorted(c.energy.items()):
            rows.append({**base, "series": series, "tag": e.tag, "total_j": e.total_j, "above_idle_j": e.above_j, "idle_w": e.idle_w,
                         "total_reason": e.total_reason, "above_reason": e.above_reason})
    return rows


