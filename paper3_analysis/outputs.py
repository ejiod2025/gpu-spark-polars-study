def paper_tables(contrasts, delta, break_even, qa, tree) -> list:
    """The Table objects with Markdown and LaTeX renderings (the CSVs of every table are written for all of them)."""
    tables = []
    text = [("Contrast", lambda r: r["contrast"].upper().replace("_STRICT", "s")), ("Host", lambda r: r["host"]), ("Suite", lambda r: r["suite"]),
            ("Scale", lambda r: r["scale"].upper()), ("Metric", lambda r: r["metric"]), ("rho [95% CI]", lambda r: with_ci(r)),
            ("Class", lambda r: (r["class"] or DASH).replace("_", " ")), ("Scopes", lambda r: f"{r['ref_scope'] or DASH} / {r['eng_scope'] or DASH}")]
    rows = contrast_rows(contrasts)
    tables.append(table("t01_x_suite_contrasts", "X1-X3: suite-level rho = reference / engine, geometric mean over queries then rounds; 95% t-interval, df = R - 1",
                        SUITE_COLUMNS, rows, text, note="rho > 1: the GPU engine uses less (time, energy, cost). Cross-class energy rows compare S1 (GPU) with "
                                                         "S2-pinned (CPU), each a node-energy lower bound: statements are worded under N1 (design 2.5)."))
    text = [("Contrast", lambda r: r["contrast"].upper().replace("_STRICT", "s")), ("Host", lambda r: r["host"]), ("Suite", lambda r: r["suite"]),
            ("Metric", lambda r: r["metric"]), ("Break-even", lambda r: r["bracket"]), ("Label", lambda r: r["label"] or DASH)]
    tables.append(table("t02_break_even", "Break-even scale: the smallest grid scale from which every larger scale is GPU better (bracket, design 5.3)",
                        BREAK_EVEN_COLUMNS, break_even_rows(break_even), text,
                        note="Energy brackets are lower bounds on the node-level break-even under N1."))
    text = [("Contrast", lambda r: r["contrast"].upper().replace("_STRICT", "s")), ("Host", lambda r: r["host"]), ("Suite", lambda r: r["suite"]),
            ("Scale", lambda r: r["scale"].upper()), ("Metric", lambda r: r["metric"]),
            ("Delta* (Wh/suite run) [95% CI]", lambda r: with_ci({"estimate": r["delta_wh_mean"], "ci_low": r["delta_wh_ci_low"], "ci_high": r["delta_wh_ci_high"]})),
            ("Delta* (W) [95% CI]", lambda r: with_ci({"estimate": r["delta_w_mean"], "ci_low": r["delta_w_ci_low"], "ci_high": r["delta_w_ci_high"]}))]
    tables.append(table("t03_delta_star", "Tipping point Delta* = E_C - E_G: how large the GPU node's unmeasured excess would have to be (design 2.5)",
                        DELTA_COLUMNS, delta_rows(delta), text))
    text = [("Host", lambda r: r["host"]), ("Engine", lambda r: r["engine"]), ("Sessions", lambda r: str(r["sessions"])), ("Pass", lambda r: str(r["pass"])),
            ("Fail", lambda r: str(r["fail"])), ("Not evaluable", lambda r: str(r["not_evaluable"])),
            ("Flagged share", lambda r: f"{r['flagged_share']:.0%}" if r["flagged_share"] is not None else DASH)]
    tables.append(table("t04_g8_by_host_engine", "G8 clock alignment: sessions per host and engine (amendment A4)", G8_COLUMNS, g8_rows(qa), text, longtable=False))
    return tables


def write_tables(directory: Path, contrasts, delta, break_even, qa, tree, x4, x5, x6, totals, store, coverage, billing, synthetic) -> list:
    directory = Path(directory)
    names = []
    for t in paper_tables(contrasts, delta, break_even, qa, tree):
        t.write(directory, synthetic)
        names.append(t.name)
    csvs = [("t05_x_query_contrasts", query_rows(contrasts), QUERY_COLUMNS), ("t06_x4_generation", x4_rows(x4), X4_COLUMNS),
            ("t07_x5_platform", x5_rows(x5), X5_COLUMNS), ("t08_x6_idle_gpu_tax", x6_rows(x6), X6_COLUMNS), ("t09_totals", totals_rows(totals), TOTALS_COLUMNS),
            ("t10_cells", cell_rows(store), CELL_COLUMNS), ("t11_coverage_matrix", coverage, COVERAGE_COLUMNS), ("t12_squares", squares_rows(tree), SQUARES_COLUMNS),
            ("t13_qa_flags", flag_rows(qa), FLAG_COLUMNS), ("t14_qa_g9_cells", g9_rows(qa), G9_COLUMNS), ("t15_qa_idle_stability", idle_rows(qa), IDLE_COLUMNS),
            ("t16_qa_attempts", attempt_rows(qa), ATTEMPT_COLUMNS),
            ("t17_billing", billing, ["instance", "host", "launch_utc", "terminate_confirmed_utc", "hours", "price_usd_per_hour", "expected_usd", "invoice_usd",
                                      "gap", "gap_above_2pct", "credit_funded"])]
    for name, rows, columns in csvs:
        write_csv(directory / f"{name}.csv", rows, columns, synthetic)
        names.append(name)
    return names


def write_qa_tables(directory: Path, qa: dict, synthetic: bool) -> list:
    directory = Path(directory)
    out = []
    for name, rows, columns in (("qa_g8_by_host_engine", g8_rows(qa), G8_COLUMNS), ("qa_flags", flag_rows(qa), FLAG_COLUMNS), ("qa_g9_cells", g9_rows(qa), G9_COLUMNS),
                                ("qa_idle_stability", idle_rows(qa), IDLE_COLUMNS), ("qa_attempts", attempt_rows(qa), ATTEMPT_COLUMNS)):
        write_csv(directory / f"{name}.csv", rows, columns, synthetic)
        out.append(name)
    return out
