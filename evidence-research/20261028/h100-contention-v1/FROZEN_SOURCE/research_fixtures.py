def table_data():
    """Return named, typed rows convenient for Spark createDataFrame or Arrow."""
    return {name: {"schema": deepcopy(TABLE_SCHEMAS[name]),
                   "rows": [dict(zip(TABLE_SCHEMAS[name], row)) for row in rows]}
            for name, rows in TABLE_ROWS.items()}


def spark_sql(query_id):
    return SQL[query_id].strip()


def register_duckdb(connection):
    """Install tiny typed tables without requiring Arrow, Pandas, or extensions."""
    for table, rows in TABLE_ROWS.items():
        columns = ", ".join(f'"{name}" {kind}' for name, kind in TABLE_SCHEMAS[table].items())
        connection.execute(f'CREATE TEMP TABLE "{table}" ({columns})')
        placeholders = ", ".join("?" for _ in TABLE_SCHEMAS[table])
        connection.executemany(f'INSERT INTO "{table}" VALUES ({placeholders})', rows)


def polars_tables():
    import polars as pl
    types = {"BIGINT": pl.Int64, "DOUBLE": pl.Float64, "VARCHAR": pl.String}
    return {name: pl.DataFrame(rows, schema={column: types[kind] for column, kind in
                TABLE_SCHEMAS[name].items()}, orient="row").lazy()
            for name, rows in TABLE_ROWS.items()}


def polars_query(query_id, tables):
    """Build a native lazy plan; caller selects CPU or strict GPU collection."""
    import polars as pl
    c = pl.col
    if query_id == "fx_inner_duplicates_nulls":
        return (tables["fx_left"].join(tables["fx_right"], on="join_key", how="inner")
                .select("left_id", "right_id").sort("left_id", "right_id"))
    if query_id == "fx_outer_counts":
        return (tables["fx_entities"].join(tables["fx_facts"], on="entity_id", how="left")
                .group_by("entity_id")
                .agg(pl.len().cast(pl.Int64).alias("joined_rows"),
                     c("fact_id").count().cast(pl.Int64).alias("nonnull_fact_ids"))
                .sort("entity_id", nulls_last=True))
    if query_id == "fx_semi_anti":
        return (tables["fx_entities"].join(tables["fx_allowed"], on="entity_id", how="semi")
                .join(tables["fx_blocked"], on="entity_id", how="anti")
                .select("entity_id").sort("entity_id", nulls_last=True))
    if query_id == "fx_rank_ties":
        return (tables["fx_scores"].with_columns(
            c("item_id").cum_count().over("group_name",
                # An explicit null flag makes SQL NULLS LAST portable across
                # Polars versions whose over() null ordering differs.
                order_by=[c("score").is_null().alias("null_score_first_key"),
                          (-c("score")).alias("descending_score_key"), c("item_id")],
                nulls_last=True)
                .cast(pl.Int64).alias("row_num"),
            pl.when(c("score").is_null())
                .then(c("score").is_not_null().sum().over("group_name") + 1)
                .otherwise(c("score").rank(method="min", descending=True).over("group_name"))
                .cast(pl.Int64).alias("score_rank"),
            c("score").shift(1).over("group_name", order_by="item_id")
                .alias("previous_score"))
            .select("group_name", "item_id", "score", "row_num", "score_rank", "previous_score")
            .sort(["group_name", "row_num"], nulls_last=True))
    if query_id == "fx_regex_distinct":
        return (tables["fx_text"].filter(~c("comment").str.contains("(?s)special.*requests"))
                .group_by("group_name")
                .agg(pl.len().cast(pl.Int64).alias("eligible_rows"),
                     c("value_id").drop_nulls().n_unique().cast(pl.Int64).alias("distinct_values"))
                .sort("group_name"))
    raise KeyError(query_id)
